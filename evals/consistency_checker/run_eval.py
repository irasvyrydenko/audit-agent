"""Eval: consistency_checker (verification step; no LLM calls).

Gold: data/gold/consistency_checker/claims.jsonl — structured claims taken from real FY2024
MD&A paragraphs with the expected verdict. Perturbed copies of every claim whose expected
verdict is "supported" are generated by perturb_claim() (flipped direction or number x0.5 /
x1.5); their expected verdict is "contradicted".
Metrics: verdict_accuracy (gold claims), perturbed_detection_rate, overall_accuracy (gold +
perturbed), confusion_matrix {gold: {pred: count}}, per_verdict {verdict: {precision,
recall, support}}.
LLM claim extraction is evaluated separately once the free quota allows (not here).
Run: python -m evals.consistency_checker.run_eval
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from audit_agent.common.config import load_settings, resolve_path
from audit_agent.consistency_checker.checker import Claim, perturb_claim, verify_claim
from audit_agent.filing_loader.loader import load_filing
from audit_agent.kpi_extractor.extractor import KPISet, load_kpis
from evals.common import write_results

COMPONENT = "consistency_checker"
VERDICTS = ("supported", "contradicted", "unverifiable")


def load_gold() -> list[dict[str, Any]]:
    path = resolve_path(load_settings().paths.gold) / COMPONENT / "claims.jsonl"
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line]


def build_cases(gold: list[dict[str, Any]], seed: int) -> list[dict[str, Any]]:
    """Gold claims plus one perturbed copy per supported claim."""
    cases = []
    for row in gold:
        claim = Claim.model_validate(row["claim"])
        cases.append(
            {
                "ticker": row["ticker"],
                "fy": row["fy"],
                "claim": claim,
                "expected": row["expected_verdict"],
                "perturbed": False,
            }
        )
        if row["expected_verdict"] == "supported":
            cases.append(
                {
                    "ticker": row["ticker"],
                    "fy": row["fy"],
                    "claim": perturb_claim(claim, seed),
                    "expected": "contradicted",
                    "perturbed": True,
                }
            )
    return cases


def score(rows: list[dict[str, Any]]) -> dict[str, Any]:
    def acc(subset: list[dict[str, Any]]) -> float | None:
        return (
            round(sum(r["expected"] == r["predicted"] for r in subset) / len(subset), 4)
            if subset
            else None
        )

    confusion = {g: {p: 0 for p in VERDICTS} for g in VERDICTS}
    for r in rows:
        confusion[r["expected"]][r["predicted"]] += 1
    per_verdict = {}
    for v in VERDICTS:
        tp = confusion[v][v]
        predicted = sum(confusion[g][v] for g in VERDICTS)
        support = sum(confusion[v].values())
        per_verdict[v] = {
            "precision": round(tp / predicted, 4) if predicted else None,
            "recall": round(tp / support, 4) if support else None,
            "support": support,
        }
    gold_rows = [r for r in rows if not r["perturbed"]]
    perturbed = [r for r in rows if r["perturbed"]]
    return {
        "verdict_accuracy": acc(gold_rows),
        "perturbed_detection_rate": acc(perturbed),
        "overall_accuracy": acc(rows),
        "confusion_matrix": confusion,
        "per_verdict": per_verdict,
    }


def main(results_root: Path | None = None) -> int:
    settings = load_settings()
    gold = load_gold()
    cases = build_cases(gold, settings.eval.random_seed)
    kpis: dict[tuple[str, int], tuple[KPISet, KPISet | None]] = {}
    rows = []
    for case in cases:
        key = (case["ticker"], case["fy"])
        if key not in kpis:
            filing = load_filing(*key)
            kpis[key] = load_kpis(case["ticker"], case["fy"], filing.ref)
        current, prior = kpis[key]
        result = verify_claim(
            case["claim"],
            current,
            prior,
            settings.consistency.numeric_tolerance,
            settings.consistency.flat_threshold,
        )
        rows.append(
            {
                "claim_id": case["claim"].id,
                "ticker": case["ticker"],
                "perturbed": case["perturbed"],
                "expected": case["expected"],
                "predicted": result.verdict,
                "rationale": result.rationale,
            }
        )
    metrics = score(rows)
    path = write_results(
        COMPONENT,
        metrics=metrics,
        dataset={
            "name": f"gold/{COMPONENT}",
            "n": len(gold),
            "n_perturbed": sum(r["perturbed"] for r in rows),
            "labeled_by": sorted({r.get("labeled_by", "?") for r in gold}),
        },
        notes="Verification only (structured gold claims, agent-drafted). LLM extraction not "
        "evaluated yet (free daily quota).",
        results_root=results_root,
    )
    predictions = path.parent / "predictions_latest.jsonl"
    predictions.write_text("\n".join(json.dumps(r) for r in rows) + "\n", encoding="utf-8")
    headline = ("verdict_accuracy", "perturbed_detection_rate", "overall_accuracy")
    print(f"{COMPONENT}: {json.dumps({k: metrics[k] for k in headline})}\n-> {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
